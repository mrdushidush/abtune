// docs/eval/<date>.md (HANDOFF §17): tables per persona and mode, §16 #3–#5, printed playlists.
import { DEFAULT_IG_NORM, DEFAULT_RAW_HOOK } from "@abtune/engine";
import type { Persona } from "./persona.ts";
import {
  DEEP_DIP,
  type EvalSettings,
  type EvalSummary,
  type PersonaModeResult,
  percentile,
  type RandomCheck,
} from "./run.ts";

export interface PrintedPlaylist {
  readonly persona: Persona;
  readonly mode: number;
  readonly title: string;
  readonly lines: readonly string[];
}

export interface ReportInput {
  readonly date: string;
  readonly catalog: {
    readonly version: string;
    readonly kind: string;
    readonly tracks: number;
    readonly loadMs: number;
  };
  readonly engineVersion: string;
  readonly settings: EvalSettings;
  readonly results: readonly PersonaModeResult[];
  readonly summary: EvalSummary;
  readonly noisy?: { readonly noise: number; readonly summary: EvalSummary };
  readonly baselines: ReadonlyMap<string, number>;
  readonly random: RandomCheck;
  readonly printed: readonly PrintedPlaylist[];
  /** §16 #5: the recorded minimum for fit(deepest) − fit(shallowest). */
  readonly marginThreshold: number;
  /** Owner decision D1: recorded minimums for canon hits per 100 tracks and the signature share. */
  readonly recognitionThresholds?: { readonly canon: number; readonly sig: number };
  /** Canon list size and how many of its songs this catalog has. */
  readonly canon?: { readonly songs: number; readonly found: number };
  readonly tuning?: {
    readonly start: EvalSummary;
    readonly changes: readonly string[];
    readonly evaluations: number;
  };
  readonly notes?: readonly string[];
}

const f3 = (x: number) => x.toFixed(3);
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

/** Hebrew personas first (owner: lead with Hebrew), then file order. */
export function reportOrder(personas: readonly Persona[]): Persona[] {
  return [...personas].sort(
    (a, b) => Number(!a.id.startsWith("hebrew_")) - Number(!b.id.startsWith("hebrew_")),
  );
}

function modeTable(summary: EvalSummary): string[] {
  return [
    "| mode | persona fit | fit2 | cluster | decade | language | scalar | diversity | artist spread | hits view | signature | canon /100 | mean year | violations |",
    "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ...summary.byMode.map(
      (m) =>
        `| ${m.mode} | **${f3(m.metrics.fit)}** | ${f3(m.metrics.fit2)} | ${f3(m.metrics.cluster)} | ${f3(m.metrics.decade)} | ${f3(m.metrics.language)} | ${f3(m.metrics.scalar)} | ${f3(m.metrics.diversity)} | ${f3(m.metrics.artistSpread)} | ${pct(m.metrics.hits)} | ${pct(m.metrics.sig)} | ${m.metrics.canon.toFixed(1)} | ${m.metrics.year.toFixed(0)} | ${m.violations} / ${m.playlists} |`,
    ),
  ];
}

export function renderReport(r: ReportInput): string {
  const personas = reportOrder([
    ...new Map(r.results.map((x) => [x.persona.id, x.persona])).values(),
  ]);
  const modes = r.summary.byMode.map((m) => m.mode);
  const passMargin = r.summary.margin >= r.marginThreshold;
  const p50 = percentile(r.random.ms50, 0.5);
  const p95 = percentile(r.random.ms50, 0.95);
  const max = r.random.ms50.at(-1) ?? 0;
  const lines: string[] = [
    `# Persona eval: ${r.date}`,
    "",
    `Generated by \`abtune eval\` (HANDOFF §17). Catalog **${r.catalog.version}** (${r.catalog.kind}, ${r.catalog.tracks.toLocaleString("en-US")} tracks),`,
    `engine ${r.engineVersion}. ${personas.length} personas × modes ${modes.join("/")} × ${r.settings.salts} seeds, ${r.settings.length}-track playlists.`,
    "",
    "## Acceptance (HANDOFF §16)",
    "",
    "| check | result | |",
    "|---|---|---|",
    `| #3 p95 generation time, 50 tracks, AI off | ${p95.toFixed(0)} ms (p50 ${p50.toFixed(0)}, max ${max.toFixed(0)}, ${r.random.ms50.length} runs) | ${p95 < 2000 ? "pass" : "**FAIL**"} |`,
    `| #4 playlists violating §9.3 | ${r.random.violations + r.summary.byMode.reduce((a, m) => a + m.violations, 0)} of ${r.random.playlists + r.summary.byMode.reduce((a, m) => a + m.playlists, 0)} | ${r.random.violations + r.summary.byMode.reduce((a, m) => a + m.violations, 0) === 0 ? "pass" : "**FAIL**"} |`,
    `| #5 mean fit rises ${modes.join(" → ")} (the last step may dip ≤ ${DEEP_DIP}) | ${r.summary.byMode.map((m) => f3(m.metrics.fit)).join(" → ")} | ${r.summary.monotone ? "pass" : "**FAIL**"} |`,
    `| #5 margin, ${modes.at(-1)} vs ${modes[0]} questions (recorded minimum ${f3(r.marginThreshold)}) | +${f3(r.summary.margin)} | ${passMargin ? "pass" : "**FAIL**"} |`,
    ...(r.recognitionThresholds
      ? [
          `| D1 canon hits per 100 tracks (recorded minimum ${r.recognitionThresholds.canon.toFixed(1)}) | ${r.summary.canon.toFixed(2)} | ${r.summary.canon >= r.recognitionThresholds.canon ? "pass" : "**FAIL**"} |`,
          `| D1 signature songs (recorded minimum ${pct(r.recognitionThresholds.sig)}) | ${pct(r.summary.sig)} | ${r.summary.sig >= r.recognitionThresholds.sig ? "pass" : "**FAIL**"} |`,
        ]
      : []),
    "",
    `Recognition (owner decision D1): **${pct(r.summary.hits)}** of persona tracks are in the hits view, **${pct(r.summary.sig)}** are one of a famous artist's top 3 songs, and there are **${r.summary.canon.toFixed(2)}** canon hits per 100 tracks${r.canon ? ` (canon: ${r.canon.found} of ${r.canon.songs} hand-picked hits are in this catalog)` : ""}. The Hebrew personas' playlists are **${pct(r.summary.hebrewShare)}** Hebrew.`,
    "",
    `Catalog load: ${(r.catalog.loadMs / 1000).toFixed(1)} s (once per process, not part of generation time). Random-listener playlists: ${r.random.playlists} (a/b/both/skip answers, random mode and length), ${r.random.short} short with \`catalog_exhausted\`.`,
    "",
    "## Mean over personas, by mode",
    "",
    ...modeTable(r.summary),
    "",
  ];
  if (r.noisy) {
    lines.push(
      `### With ${pct(r.noisy.noise)} of answers flipped (robustness)`,
      "",
      ...modeTable(r.noisy.summary),
      "",
      `Rises with depth: ${r.noisy.summary.monotone ? "yes" : "**no**"}; margin +${f3(r.noisy.summary.margin)}.`,
      "",
    );
  }
  lines.push(
    "## Persona fit by mode",
    "",
    "Fit per track = cluster share × decade weight × language weight × share of scalar ranges met, averaged over the playlist and seeds. Baseline = a uniformly random catalog track.",
    "",
    `| persona | baseline | ${modes.map((m) => `${m} q`).join(" | ")} | answered |`,
    `|---|---:|${modes.map(() => "---:").join("|")}|---|`,
  );
  for (const p of personas) {
    const rows = modes.map((m) => r.results.find((x) => x.persona.id === p.id && x.mode === m));
    lines.push(
      `| ${p.name} | ${f3(r.baselines.get(p.id) ?? 0)} | ${rows.map((x) => (x ? f3(x.metrics.fit) : "–")).join(" | ")} | ${rows.map((x) => (x ? `${x.answered}${x.exhausted ? "*" : ""}` : "–")).join(" / ")} |`,
    );
  }
  lines.push(
    "",
    "\\* the bank ran out of questions this persona would answer (skips burn questions).",
    "",
    "### Fit components at the deepest mode",
    "",
    "| persona | cluster | decade | language | scalar | diversity | artist spread | median popularity |",
    "|---|---:|---:|---:|---:|---:|---:|---:|",
  );
  for (const p of personas) {
    const x = r.results.find((y) => y.persona.id === p.id && y.mode === modes.at(-1));
    if (!x) continue;
    const m = x.metrics;
    lines.push(
      `| ${p.name} | ${f3(m.cluster)} | ${f3(m.decade)} | ${f3(m.language)} | ${f3(m.scalar)} | ${f3(m.diversity)} | ${f3(m.artistSpread)} | ${pct(m.popularity)} |`,
    );
  }
  lines.push(
    "",
    "### Recognition by persona (all modes)",
    "",
    "| persona | hits view | signature | canon /100 | Hebrew | fit2 |",
    "|---|---:|---:|---:|---:|---:|",
  );
  for (const p of personas) {
    const rows = r.results.filter((x) => x.persona.id === p.id);
    const avg = (k: "hits" | "sig" | "canon" | "hebrew" | "fit2") =>
      rows.length ? rows.reduce((a, x) => a + x.metrics[k], 0) / rows.length : 0;
    lines.push(
      `| ${p.name} | ${pct(avg("hits"))} | ${pct(avg("sig"))} | ${avg("canon").toFixed(1)} | ${pct(avg("hebrew"))} | ${f3(avg("fit2"))} |`,
    );
  }
  lines.push(
    "",
    "## Settings",
    "",
    "```json",
    JSON.stringify(
      {
        taste: r.settings.taste,
        generator: r.settings.generator,
        select: {
          igNorm: r.settings.select.igNorm ?? DEFAULT_IG_NORM,
          rawHook: r.settings.select.rawHook ?? DEFAULT_RAW_HOOK,
        },
      },
      null,
      2,
    ),
    "```",
    "",
  );
  if (r.tuning) {
    lines.push(
      "## Tuning",
      "",
      `Coordinate search, ${r.tuning.evaluations} evaluations. Start: fit ${f3(r.tuning.start.meanFit)}, margin +${f3(r.tuning.start.margin)}, rises with depth: ${r.tuning.start.monotone ? "yes" : "no"}.`,
      "",
      ...(r.tuning.changes.length > 0
        ? r.tuning.changes.map((c) => `- ${c}`)
        : ["- no change beat the start"]),
      "",
    );
  }
  if (r.notes && r.notes.length > 0)
    lines.push("## Notes", "", ...r.notes.map((n) => `- ${n}`), "");
  lines.push("## Playlists", "", "Seed 0 of each persona, for eyeballing.", "");
  for (const pl of r.printed) {
    lines.push(
      `<details><summary>${pl.persona.name}: ${pl.mode} questions · ${pl.title}</summary>`,
      "",
      ...pl.lines.map((l, i) => `${i + 1}. ${l}`),
      "",
      "</details>",
      "",
    );
  }
  return lines.join("\n");
}
